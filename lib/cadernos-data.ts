// Função para obter cadernos principais (sem parent)
export function getMainCadernos(): Caderno[] {
  return CADERNOS_HIERARCHY.filter((c) => !c.parentId)
}

// Função para obter sub-cadernos de um caderno
export function getSubCadernos(parentId: string): Caderno[] {
  return CADERNOS_HIERARCHY.filter((c) => c.parentId === parentId)
}

// Função para obter um caderno por ID
export function getCadernoById(id: string): Caderno | undefined {
  return CADERNOS_HIERARCHY.find((c) => c.id === id)
}

// Função para calcular progresso de um caderno (deve ser chamada apenas no cliente)
export function calculateCadernoProgress(cadernoId: string): number {
  // Verificar se estamos no cliente
  if (typeof window === "undefined") return 0

  const caderno = getCadernoById(cadernoId)
  if (!caderno || caderno.questions.length === 0) return 0

  try {
    const answers = localStorage.getItem(`caderno-answers-${cadernoId}`)
    if (!answers) return 0

    const parsedAnswers = JSON.parse(answers)
    const answeredCount = Object.keys(parsedAnswers).filter(
      (key) => parsedAnswers[key] && parsedAnswers[key].toString().trim() !== "",
    ).length

    return Math.round((answeredCount / caderno.questions.length) * 100)
  } catch {
    return 0
  }
}
